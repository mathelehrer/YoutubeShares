from collections import OrderedDict

import numpy as np

from compositions.compositions import create_glow_composition
from interface import ibpy
from interface.ibpy import Vector, Matrix, Quaternion
from interface.interface_constants import BLENDER_EEVEE
from new_stuff.geometry_nodes_modifier import Poly600CellStereoModifier
from objects.empties import EmptyCube
from objects.plane import Plane
from objects.polytopes import Poly600Cell
from objects.text2 import Text
from perform.scene import Scene
from utils.utils import print_time_report

pi = np.pi
tau=2*pi

class Cell600(Scene):
    def __init__(self):
        self.t0 = None
        self.construction_counter = 0
        self.old = None
        self.sub_scenes = OrderedDict([
            ('stereo_projection',{'duration':62}),
            ('cell_projection',{'duration':62}),

        ])
        super().__init__(light_energy=2, transparent=False)

    def stereo_projection(self):
        t0 = 0
        ibpy.set_hdri_background("qwantani_puresky_4k", 'exr', simple=True,
                                 transparent=True,
                                 rotation_euler=pi / 180 * Vector())
        t0 = ibpy.set_hdri_strength(1, begin_time=t0, transition_time=1)
        ibpy.set_render_engine(denoising=False, transparent=False, frame_start=1,  # skip initialization frame at 0
                               resolution_percentage=100, engine=BLENDER_EEVEE, taa_render_samples=512,
                               motion_blur=False)

        camera_empty = EmptyCube(location=Vector([0, 0, 0]))
        camera_location = [0, -27, 0]
        ibpy.set_camera_location(location=camera_location)
        ibpy.set_camera_view_to(camera_empty)
        ibpy.set_camera_lens(lens=300)

        create_glow_composition(threshold=1, type="BLOOM", size=4)

        cell = Poly600Cell(offset=0.05,scale=2)
        modifier = Poly600CellStereoModifier(csv_file="poly600cell.csv",face_color="c600_material",edge_color="plastic_example")
        cell.add_mesh_modifier(type="NODES",node_modifier=modifier)

        cell.rotate("Theta0",from_angle=0,to_angle=tau,begin_time=t0,transition_time=20,modifier=modifier)
        ibpy.camera_zoom(lens=40,begin_time=t0,transition_time=10)
        zoom_finished= t0+10
        t0 = 0.5 + cell.grow(begin_time=t0, transition_time=20,modifier=modifier)

        cell.change_alpha(from_value=1,to_value=0.2,begin_time=t0,transition_time=5,modifier=modifier)
        cell.rotate("Theta2",from_angle=0,to_angle=tau,begin_time=t0,transition_time=15,modifier=modifier)
        cell.rotate("Theta3",from_angle=0,to_angle=tau,begin_time=t0+15,transition_time=15,modifier=modifier)
        cell.change_alpha(from_value=0.2,to_value=1,begin_time=t0+15,transition_time=5,modifier=modifier)
        t0 = 0.5 + cell.rotate("Theta5", from_angle=0, to_angle=tau, begin_time=t0, transition_time=30, modifier=modifier)

        title = Text(r"\text{Geometry generated by: }",aligned="center",text_size="Large")
        title.move_to(target_location=[0, 0, 10], begin_time=zoom_finished, transition_time=0)
        zoom_finished=0.5 + title.write(begin_time=zoom_finished,transition_time=0.3)
        q1 = Text(r"\omega = -\tfrac{1}{2}+\tfrac{1}{2} i +\tfrac{1}{2} j+ \tfrac{1}{2}+k",aligned="centered",text_size="Large")
        q1.move_to(target_location=[-3.5, 0, 8.5], begin_time=zoom_finished, transition_time=0)
        zoom_finished=0.5 + q1.write(begin_time=zoom_finished,transition_time=0.3)
        q2 = Text(r"q = -\tfrac{1}{2} i +\tfrac{1}{4}\left(\sqrt{5}+1\right) j +\tfrac{1}{4}\left(\sqrt{5}-1\right)k",aligned="centered",text_size="Large")
        q2.move_to(target_location=[-3.5, 0, 7], begin_time=zoom_finished, transition_time=0)
        zoom_finished=0.5 + q2.write(begin_time=zoom_finished,transition_time=0.3)


        legend = Text(r"\text{4D: }w \in [-1,1]",aligned="center",text_size="Large")
        legend.move_to(target_location=[0,0,-9],begin_time=0,transition_time=0)
        legend.write(begin_time=zoom_finished,transition_time=0.3)
        plane = Plane(rotation_euler=Vector([pi/2,0,0]),color="c600_gradient",scale=[5,0.5,1])
        plane.move_to(target_location=[0,0,-10],begin_time=0,transition_time=0)
        plane.appear(begin_time=zoom_finished,transition_time=1)
        self.t0 = t0

    def cell_projection(self):
        t0 = 0
        ibpy.set_hdri_background("forest", 'exr', simple=True,
                                 transparent=True,
                                 rotation_euler=[0, 0, 0])
        t0 = ibpy.set_hdri_strength(1, begin_time=t0, transition_time=0)
        ibpy.set_render_engine(denoising=False, transparent=True, frame_start=1,  # skip initialization frame at 0
                               resolution_percentage=100, engine=BLENDER_EEVEE, taa_render_samples=1024,
                               motion_blur=False)

        camera_empty = EmptyCube(location=Vector([0, 0, 0]))
        camera_location = [0, -20, 0]
        ibpy.set_camera_location(location=camera_location)
        ibpy.set_camera_view_to(camera_empty)
        ibpy.set_camera_lens(lens=40)

        create_glow_composition(threshold=1, type="BLOOM", size=1)

        cell = Poly600Cell(color="joker",offset=0.05)
        t0 = 0.5 + cell.appear(alpha=0.15,begin_time=t0, transition_time=0.5)

        self.t0 = t0

